static int pico8_inext (lua_State *L) {
  luaL_checktype(L, 1, LUA_TTABLE);
  int i;
  if (lua_isnil(L, 2)){
    i = 0;
    lua_pushinteger(L, i);
  }
  else {
    i = luaL_checkint(L, 2);
  }
  i++;  /* next value */
  lua_pushinteger(L, i);
  lua_rawgeti(L, 1, i);
  return (lua_isnil(L, -1)) ? 1 : 2;
}

