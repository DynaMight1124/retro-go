/*
=================
WriteLevel

=================
*/
void WriteLevel (char *filename)
{
	int		i;
	edict_t	*ent;
	FILE	*f;

	f = fopen (filename, "wb");
	if (!f)
		gi.error ("Couldn't open %s", filename);

	// write out edict size for checking
	if (!Q2_SaveWriteHeader(f))
	{
		fclose(f);
		gi.error ("Couldn't write level header: %s", filename);
		return;
	}
	i = sizeof(edict_t);
	SaveWrite(f, &i, sizeof(i));

	// write out level_locals_t
	WriteLevelLocals (f);

	// write out all the entities
	for (i=0 ; i<globals.num_edicts ; i++)
	{
		ent = &g_edicts[i];
		if (!ent->inuse)
			continue;
		SaveWrite(f, &i, sizeof(i));
		WriteEdict (f, ent);
	}
	i = -1;
	SaveWrite(f, &i, sizeof(i));

	SaveClose(f);
}


/*
=================
ReadLevel

SpawnEntities will allready have been called on the
level the same way it was when the level was saved.

That is necessary to get the baselines
set up identically.

The server will have cleared all of the world links before
calling ReadLevel.

No clients are connected yet.
=================
*/
void ReadLevel (char *filename)
{
	int		entnum;
	FILE	*f;
	int		i;
	edict_t	*ent;

	f = fopen (filename, "rb");
	if (!f)
		gi.error ("Couldn't open %s", filename);

	// free any dynamic memory allocated by loading the level
	if (!Q2_SaveReadHeader(f))
	{
		fclose(f);
		gi.error ("Level save incompatible with this firmware. Create a new save.\n");
		return;
	}
	// Check the fixed layout before freeing or clearing any running state.
	SaveRead(f, &i, sizeof(i));
	if (i != sizeof(edict_t))
		SaveError(f, "mismatched edict size");
	// base state
	gi.FreeTags (TAG_LEVEL);

	// wipe all the entities
	memset (g_edicts, 0, game.maxentities*sizeof(g_edicts[0]));
	globals.num_edicts = maxclients->value+1;

	// load the level locals
	ReadLevelLocals (f);

	// load all the entities
	while (1)
	{
		SaveRead(f, &entnum, sizeof(entnum));
		if (entnum == -1)
			break;
		if (entnum < 0 || entnum >= game.maxentities)
			SaveError(f, "invalid entity number");
		if (entnum >= globals.num_edicts)
			globals.num_edicts = entnum+1;

		ent = &g_edicts[entnum];
		ReadEdict (f, ent);

		// let the server rebuild world links for this ent
		memset (&ent->area, 0, sizeof(ent->area));
		gi.linkentity (ent);
	}

	SaveClose(f);

	// mark all clients as unconnected
	for (i=0 ; i<maxclients->value ; i++)
	{
		ent = &g_edicts[i+1];
		ent->client = game.clients + i;
		ent->client->pers.connected = false;
	}

	// do any load time things at this point
	for (i=0 ; i<globals.num_edicts ; i++)
	{
		ent = &g_edicts[i];

		if (!ent->inuse)
			continue;

		// fire any cross-level triggers
		if (ent->classname)
			if (strcmp(ent->classname, "target_crosslevel_target") == 0)
				ent->nextthink = level.time + ent->delay;
	}
}

