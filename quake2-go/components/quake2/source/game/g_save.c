// Native save I/O helpers. gi.error drops the current frame via longjmp:
// close the file here, rather than relying on cleanup after that call.
static void SaveError(FILE *f, const char *message)
{
	if (f) fclose(f);
	gi.error("Damaged save or storage error: %s", message);
}

static void SaveRead(FILE *f, void *data, size_t size)
{
	if (fread(data, 1, size, f) != size)
		SaveError(f, "truncated payload");
}

static void SaveWrite(FILE *f, const void *data, size_t size)
{
	if (fwrite(data, 1, size, f) != size)
		SaveError(f, "could not write payload");
}

static void SaveClose(FILE *f)
{
	if (fclose(f) != 0)
		gi.error("Could not close native save");
}

void WriteField1 (FILE *f, field_t *field, byte *base)
{
	void		*p;
	int			len;
	int			index;

	if (field->flags & FFL_SPAWNTEMP)
		return;

	p = (void *)(base + field->ofs);
	switch (field->type)
	{
	case F_INT:
	case F_FLOAT:
	case F_ANGLEHACK:
	case F_VECTOR:
	case F_IGNORE:
		break;

	case F_LSTRING:
	case F_GSTRING:
		if ( *(char **)p )
			len = strlen(*(char **)p) + 1;
		else
			len = 0;
		*(int *)p = len;
		break;
	case F_EDICT:
		if ( *(edict_t **)p == NULL)
			index = -1;
		else
			index = *(edict_t **)p - g_edicts;
		*(int *)p = index;
		break;
	case F_CLIENT:
		if ( *(gclient_t **)p == NULL)
			index = -1;
		else
			index = *(gclient_t **)p - game.clients;
		*(int *)p = index;
		break;
	case F_ITEM:
		if ( *(edict_t **)p == NULL)
			index = -1;
		else
			index = *(gitem_t **)p - itemlist;
		*(int *)p = index;
		break;

	case F_FUNCTION:
	case F_MMOVE:
	{
		uintptr_t pointer;
		uint32_t symbol;
		memcpy(&pointer, p, sizeof(pointer));
		if (!Q2_SaveEncodePointer(pointer, field->type == F_MMOVE, &symbol))
			SaveError(f, "unregistered symbol");
		memcpy(p, &symbol, sizeof(symbol));
		break;
	}

	default:
		SaveError(f, "unknown field type");
	}
}


void WriteField2 (FILE *f, field_t *field, byte *base)
{
	int			len;
	void		*p;

	if (field->flags & FFL_SPAWNTEMP)
		return;

	p = (void *)(base + field->ofs);
	switch (field->type)
	{
	case F_LSTRING:
		if ( *(char **)p )
		{
			len = strlen(*(char **)p) + 1;
			SaveWrite(f, *(char **)p, (size_t)len);
		}
		break;
	}
}

void ReadField (FILE *f, field_t *field, byte *base)
{
	void		*p;
	int			len;
	int			index;

	if (field->flags & FFL_SPAWNTEMP)
		return;

	p = (void *)(base + field->ofs);
	switch (field->type)
	{
	case F_INT:
	case F_FLOAT:
	case F_ANGLEHACK:
	case F_VECTOR:
	case F_IGNORE:
		break;

	case F_LSTRING:
		len = *(int *)p;
		// Keep map messages compatible, while bounding corrupt allocations.
		if (len < 0 || len > 256 * 1024)
			SaveError(f, "invalid string length");
		if (!len)
			*(char **)p = NULL;
		else
		{
			*(char **)p = gi.TagMalloc (len, TAG_LEVEL);
			SaveRead(f, *(char **)p, (size_t)len);
			if ((*(char **)p)[len - 1] != 0)
				SaveError(f, "unterminated string");
		}
		break;
	case F_EDICT:
		index = *(int *)p;
		if (index < -1 || index >= game.maxentities)
			SaveError(f, "invalid entity index");
		if ( index == -1 )
			*(edict_t **)p = NULL;
		else
			*(edict_t **)p = &g_edicts[index];
		break;
	case F_CLIENT:
		index = *(int *)p;
		if (index < -1 || index >= game.maxclients)
			SaveError(f, "invalid client index");
		if ( index == -1 )
			*(gclient_t **)p = NULL;
		else
			*(gclient_t **)p = &game.clients[index];
		break;
	case F_ITEM:
		index = *(int *)p;
		if (index < -1 || index >= game.num_items)
			SaveError(f, "invalid item index");
		if ( index == -1 )
			*(gitem_t **)p = NULL;
		else
			*(gitem_t **)p = &itemlist[index];
		break;

	case F_FUNCTION:
	case F_MMOVE:
	{
		uintptr_t pointer;
		uint32_t symbol;
		memcpy(&symbol, p, sizeof(symbol));
		if (!Q2_SaveDecodePointer(symbol, field->type == F_MMOVE, &pointer))
			SaveError(f, "unknown save symbol");
		memcpy(p, &pointer, sizeof(pointer));
		break;
	}

	default:
		SaveError(f, "unknown field type");
	}
}

