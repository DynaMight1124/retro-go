/*
==============
WriteClient

All pointer variables (except function pointers) must be handled specially.
==============
*/
void WriteClient (FILE *f, gclient_t *client)
{
	field_t		*field;
	gclient_t	temp;
	
	// all of the ints, floats, and vectors stay as they are
	temp = *client;

	// change the pointers to lengths or indexes
	for (field=clientfields ; field->name ; field++)
	{
		WriteField1 (f, field, (byte *)&temp);
	}

	// write the block
	SaveWrite(f, &temp, sizeof(temp));

	// now write any allocated data following the edict
	for (field=clientfields ; field->name ; field++)
	{
		WriteField2 (f, field, (byte *)client);
	}
}

/*
==============
ReadClient

All pointer variables (except function pointers) must be handled specially.
==============
*/
void ReadClient (FILE *f, gclient_t *client)
{
	field_t		*field;

	SaveRead(f, client, sizeof(*client));

	for (field=clientfields ; field->name ; field++)
	{
		ReadField (f, field, (byte *)client);
	}
}

/*
============
WriteGame

This will be called whenever the game goes to a new level,
and when the user explicitly saves the game.

Game information include cross level data, like multi level
triggers, help computer info, and all client states.

A single player death will automatically restore from the
last save position.
============
*/
void WriteGame (char *filename, qboolean autosave)
{
	FILE	*f;
	int		i;
	game_locals_t saved;

	if (!autosave)
		SaveClientData ();

	f = fopen (filename, "wb");
	if (!f)
		gi.error ("Couldn't open %s", filename);

	if (!Q2_SaveWriteHeader(f))
	{
		fclose(f);
		gi.error ("Couldn't write save header: %s", filename);
		return;
	}

	saved = game;
	saved.autosaved = autosave;
	SaveWrite(f, &saved, sizeof(saved));

	for (i=0 ; i<game.maxclients ; i++)
		WriteClient (f, &game.clients[i]);

	SaveClose(f);
}

void ReadGame (char *filename)
{
	FILE	*f;
	int		i;
	game_locals_t saved;

	f = fopen (filename, "rb");
	if (!f)
		gi.error ("Couldn't open %s", filename);

	if (!Q2_SaveReadHeader(f))
	{
		fclose(f);
		gi.error ("Savegame incompatible with this firmware. Create a new save.\n");
		return;
	}

	SaveRead(f, &saved, sizeof(saved));
	if (saved.maxclients < 1 || saved.maxclients > MAX_CLIENTS ||
		saved.maxentities <= saved.maxclients || saved.maxentities > MAX_EDICTS ||
		saved.maxclients != game.maxclients || saved.maxentities != game.maxentities ||
		saved.num_items != game.num_items ||
		!memchr(saved.helpmessage1, 0, sizeof(saved.helpmessage1)) ||
		!memchr(saved.helpmessage2, 0, sizeof(saved.helpmessage2)) ||
		!memchr(saved.spawnpoint, 0, sizeof(saved.spawnpoint)))
		SaveError(f, "invalid game metadata");
	// Reject short client blocks before freeing the running game's memory.
	long payload = ftell(f);
	if (payload < 0 || fseek(f, 0, SEEK_END) != 0 ||
		ftell(f) - payload < (long)(saved.maxclients * sizeof(gclient_t)) ||
		fseek(f, payload, SEEK_SET) != 0)
		SaveError(f, "truncated client blocks");
	gi.FreeTags (TAG_GAME);
	game = saved;
	g_edicts = gi.TagMalloc (game.maxentities * sizeof(g_edicts[0]), TAG_GAME);
	globals.edicts = g_edicts;
	globals.max_edicts = game.maxentities;
	game.clients = gi.TagMalloc (game.maxclients * sizeof(game.clients[0]), TAG_GAME);
	for (i=0 ; i<game.maxclients ; i++)
		ReadClient (f, &game.clients[i]);

	SaveClose(f);
}

